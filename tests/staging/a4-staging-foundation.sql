CREATE OR REPLACE FUNCTION public.arkhe_siguiente_numero_ronda(p_investigacion_id uuid)
RETURNS integer
LANGUAGE plpgsql
AS $$
DECLARE
  siguiente integer;
BEGIN
  PERFORM pg_advisory_xact_lock(hashtextextended(p_investigacion_id::text, 0));
  SELECT COALESCE(MAX(numero), 0) + 1 INTO siguiente
  FROM public.rondas_investigacion
  WHERE investigacion_id = p_investigacion_id;
  RETURN siguiente;
END;
$$;

CREATE OR REPLACE FUNCTION public.arkhe_insert_intervencion_ronda(
  p_ronda_id uuid,
  p_investigador_id uuid,
  p_tipo text,
  p_contenido text,
  p_responde_a_intervencion_id uuid DEFAULT NULL::uuid,
  p_nodo_id bigint DEFAULT NULL::bigint,
  p_metadata jsonb DEFAULT '{}'::jsonb
)
RETURNS public.intervenciones_ronda
LANGUAGE plpgsql
SET search_path TO 'public'
AS $$
DECLARE
  v_orden integer;
  v_intervencion public.intervenciones_ronda;
BEGIN
  PERFORM 1 FROM public.rondas_investigacion WHERE id = p_ronda_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Ronda % no encontrada.', p_ronda_id;
  END IF;
  SELECT COALESCE(MAX(orden), 0) + 1 INTO v_orden
  FROM public.intervenciones_ronda
  WHERE ronda_id = p_ronda_id;
  INSERT INTO public.intervenciones_ronda (
    ronda_id, investigador_id, orden, tipo, contenido,
    responde_a_intervencion_id, nodo_id, metadata
  ) VALUES (
    p_ronda_id, p_investigador_id, v_orden, p_tipo, p_contenido,
    p_responde_a_intervencion_id, p_nodo_id, COALESCE(p_metadata, '{}'::jsonb)
  )
  RETURNING * INTO v_intervencion;
  RETURN v_intervencion;
END;
$$;

