CREATE TABLE public.investigadores (
  id uuid PRIMARY KEY,
  nombre text NOT NULL UNIQUE,
  tipo text NOT NULL CHECK (tipo IN ('humano','ia')),
  descripcion text,
  estado text NOT NULL DEFAULT 'disponible'
    CHECK (estado IN ('disponible','ocupado','inactivo','error')),
  ultima_actividad timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.areas_arkhe (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  nombre text NOT NULL UNIQUE,
  descripcion text,
  area_padre_id uuid REFERENCES public.areas_arkhe(id) ON DELETE SET NULL,
  activa boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.investigaciones_proyecto (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  titulo text NOT NULL,
  objetivo text NOT NULL,
