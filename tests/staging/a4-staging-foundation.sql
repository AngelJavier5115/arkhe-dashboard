CREATE TABLE public.participaciones (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  investigacion_id uuid NOT NULL REFERENCES public.investigaciones_proyecto(id) ON DELETE CASCADE,
  investigador_id uuid NOT NULL REFERENCES public.investigadores(id) ON DELETE CASCADE,
